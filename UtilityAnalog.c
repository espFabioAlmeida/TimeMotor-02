#define MAX_ADC 1023
/*==============================================================================
LEITURA DO TEMPO                                        
==============================================================================*/
void leTempo() {
    unsigned int32 valorAnalog = read_adc();
    unsigned int32 range = TEMPO_MAX_H - TEMPO_MIN_H;
    valorAnalog *= range;
    valorAnalog /= MAX_ADC;

    setpointTempoHorario = valorAnalog + TEMPO_MIN_H;
}
